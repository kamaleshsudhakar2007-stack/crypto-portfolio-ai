import { useState } from 'react'
import { AlertTriangle, CheckCircle2, Info, Sparkles } from 'lucide-react'
import { api } from '../api'
import { useApi } from '../lib/useApi'
import { Card, ErrorBox, PageHeader, Skeleton, SourceBadge } from '../components/ui'
import { dateTime } from '../lib/format'

const ICON = { warning: [AlertTriangle, 'text-amber-300'], positive: [CheckCircle2, 'text-emerald-400'], info: [Info, 'text-sky-300'] }

export default function Insights() {
  const health = useApi(api.health)
  const base = useApi(() => api.insights(false))
  const [ai, setAi] = useState(null)
  const [aiBusy, setAiBusy] = useState(false)
  const [aiErr, setAiErr] = useState(null)

  const run = async () => {
    setAiBusy(true); setAiErr(null)
    try { setAi(await api.insights(true)) } catch (e) { setAiErr(e.message) } finally { setAiBusy(false) }
  }
  const data = ai || base.data
  const aiConfigured = health.data?.aiConfigured

  if (base.error && !base.data) return <ErrorBox message={base.error} onRetry={base.reload} />
  return (
    <>
      <PageHeader title="AI Insights" subtitle="Educational observations about your portfolio">
        {data && <SourceBadge source={data.source} updatedAt={data.generatedAt} />}
        <button className="btn-primary" onClick={run} disabled={!aiConfigured || aiBusy} title={aiConfigured ? '' : 'Set GEMINI_API_KEY on the backend to enable'}>
          <Sparkles size={16} /> {aiBusy ? 'Generating…' : 'Generate AI summary'}
        </button>
      </PageHeader>

      <div className="mb-4 rounded-lg border border-line bg-panel p-3 text-sm text-slate-300">
        Mode: <strong className="text-ink">{data?.mode ?? '…'}</strong>.{' '}
        {!aiConfigured && health.data && 'No AI key is configured on the server, so only rule-based insights (fixed rules, not an AI model) are shown.'}
      </div>
      {aiErr && <div className="mb-4"><ErrorBox message={aiErr} /></div>}
      {data?.aiNotice && <p className="mb-4 rounded-lg border border-amber-500/40 bg-amber-500/10 p-3 text-sm text-amber-200">{data.aiNotice}</p>}

      {data?.aiSummary && (
        <Card title={`AI-generated summary · ${data.aiProvider}`} className="mb-4">
          <p className="whitespace-pre-line text-sm leading-relaxed text-slate-200">{data.aiSummary}</p>
          <p className="mt-2 text-xs text-slate-500">Generated by an AI model from your allocation and return figures. It may contain mistakes.</p>
        </Card>
      )}

      <Card title="Rule-based insights (not AI)">
        {base.loading ? <div className="space-y-3"><Skeleton className="h-12" /><Skeleton className="h-12" /></div> : (
          <ul className="space-y-3">
            {data.insights.map((i, n) => {
              const [Icon, cls] = ICON[i.severity] || ICON.info
              return (
                <li key={n} className="flex gap-3 rounded-lg border border-line p-3">
                  <Icon size={20} className={`mt-0.5 shrink-0 ${cls}`} />
                  <div><p className="font-medium text-ink">{i.title}</p><p className="text-sm text-slate-400">{i.text}</p></div>
                </li>
              )
            })}
          </ul>
        )}
      </Card>
      {data && <p className="mt-4 text-xs text-slate-500">{data.disclaimer} Generated {dateTime(data.generatedAt)}.</p>}
    </>
  )
}
